export function initI18n() {
  const params = new URLSearchParams(window.location.search);
  const urlLang = params.get('lang');
  const saved = localStorage.getItem('zl_lang');
  let lang = urlLang || saved || 'en';
  if (!DICT[lang]) lang = 'en';

  document.querySelectorAll('[data-git-link]').forEach(el => {
    el.setAttribute('href', GITHUB_REPO_URL);
    if (GITHUB_REPO_URL.startsWith('http')) {
      el.setAttribute('target', '_blank');
      el.setAttribute('rel', 'noopener noreferrer');
    }
  });

  function apply(targetLang) {
    if (!DICT[targetLang]) return;
    lang = targetLang;
    localStorage.setItem('zl_lang', lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;
    const table = DICT[lang];
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (table[key] !== undefined) el.textContent = table[key];
    });
    document.querySelectorAll('.lang-btn').forEach(btn => {
      btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
    });
    window.dispatchEvent(new CustomEvent('zl-lang-change', { detail: { lang } }));
  }

  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => apply(btn.getAttribute('data-lang')));
  });

  apply(lang);
  return { getLang: () => lang, setLang: apply };
}
